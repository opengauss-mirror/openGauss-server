CREATE TABLE pp_f(col1 int,col2 int,col3 int,amount int);
INSERT INTO pp_f SELECT 1+g%100,1+(g/100)%10,1+(g/1000)%5,g%97 FROM generate_series(1,5000) g;
CREATE INDEX pp_f_idx ON pp_f(col1,col2);
CREATE TABLE pp_gap AS SELECT * FROM pp_f;
