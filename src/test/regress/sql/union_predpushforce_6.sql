CREATE TABLE pp_y AS SELECT * FROM pp_f;
CREATE INDEX pp_y_idx ON pp_y(col2);
CREATE TABLE pp_noidx AS SELECT * FROM pp_f;
CREATE TABLE pp_incl (LIKE pp_f) WITH (storage_type=ustore);
INSERT INTO pp_incl SELECT * FROM pp_f;
CREATE INDEX pp_incl_idx ON pp_incl USING ubtree(col1) INCLUDE(col3);
CREATE TABLE pp_reorder(col2 int,col1 int,col3 int,amount int);
INSERT INTO pp_reorder SELECT col2,col1,col3,amount FROM pp_f;
CREATE INDEX pp_reorder_idx ON pp_reorder(col1,col2);
ANALYZE pp_reorder;
ANALYZE pp_a; ANALYZE pp_b; ANALYZE pp_f; ANALYZE pp_gap;
ANALYZE pp_y; ANALYZE pp_noidx; ANALYZE pp_incl;

